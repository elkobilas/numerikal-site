let currentLang = localStorage.getItem('numerikal-lang') || 'fr';

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('numerikal-lang', lang);
  document.documentElement.lang = lang;
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  const flag = document.querySelector('.lang-flag');
  if (flag) flag.textContent = lang === 'fr' ? 'EN' : 'FR';
  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.setAttribute('aria-label', lang === 'fr' ? 'Switch to English' : 'Passer en français');
}

document.addEventListener('DOMContentLoaded', () => {
  const y = document.getElementById('year');
  if (y) y.textContent = new Date().getFullYear();

  applyLang(currentLang);

  const langToggle = document.getElementById('langToggle');
  if (langToggle) {
    langToggle.addEventListener('click', () => {
      applyLang(currentLang === 'fr' ? 'en' : 'fr');
    });
  }

  const menuBtn = document.getElementById('menuBtn');
  const mobileMenu = document.getElementById('mobileMenu');
  if (menuBtn && mobileMenu) {
    menuBtn.addEventListener('click', () => mobileMenu.classList.toggle('open'));
    mobileMenu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => mobileMenu.classList.remove('open')));
  }

  const revealEls = document.querySelectorAll('.section, .hero-copy, .hero-visual, .course-card, .yt-card, .info-card, .contact-item, .short-card');
  revealEls.forEach(el => el.classList.add('reveal'));
  const io = new IntersectionObserver((entries) => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        e.target.classList.add('visible');
        io.unobserve(e.target);
      }
    });
  }, { threshold: 0.12 });
  revealEls.forEach(el => io.observe(el));

  const form = document.getElementById('contactForm');
  const note = document.getElementById('formNote');
  if (form) {
    form.addEventListener('submit', (e) => {
      e.preventDefault();
      const data = new FormData(form);
      const name = (data.get('name') || '').toString().trim();
      const email = (data.get('email') || '').toString().trim();
      const message = (data.get('message') || '').toString().trim();
      const emailOk = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
      if (!name || !emailOk || !message) {
        note.textContent = translations[currentLang]['form.error'];
        note.hidden = false;
        note.style.color = '#f87171';
        return;
      }
      note.textContent = translations[currentLang]['form.success'];
      note.hidden = false;
      note.style.color = 'var(--accent-2)';
      form.reset();
    });
  }

  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-links a');
  const spy = new IntersectionObserver((entries) => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        const id = e.target.id;
        navLinks.forEach(l => l.style.color = l.getAttribute('href') === '#' + id ? 'var(--text)' : '');
      }
    });
  }, { rootMargin: '-40% 0px -55% 0px' });
  sections.forEach(s => spy.observe(s));
});